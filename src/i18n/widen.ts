/**
 * Расширение литеральных типов словаря.
 *
 * Словари объявлены через `as const`: без этого пропали бы кортежи — строки
 * настроек вида `['Рост', '178 см', '']` и пары `['cut', 'снижение']`,
 * к которым код обращается по индексу. Но `as const` заодно превращает каждую
 * строку в её собственный тип, и второй словарь перестаёт подходить под
 * первый: «Today» — это не «Сегодня».
 *
 * Widen снимает ровно эту разницу: строки становятся строками, кортежи
 * остаются кортежами.
 */
export type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly unknown[]
        ? { [K in keyof T]: Widen<T[K]> }
        : T extends object
          ? { [K in keyof T]: Widen<T[K]> }
          : T;
