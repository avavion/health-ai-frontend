import type { Route } from 'next';

/**
 * Приведение собранного адреса к типу маршрута.
 *
 * В проекте включён typedRoutes: Next проверяет ссылки по дереву страниц. Для
 * литералов это удобно, но адрес с параметром собирается из строк, и вывести
 * его тип неоткуда. Одна честная точка приведения лучше россыпи `as` по коду —
 * по ней видно, где типизация маршрутов заканчивается.
 */
export function route(href: string): Route {
  return href as Route;
}
